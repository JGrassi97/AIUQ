#!/usr/bin/env python3
from __future__ import annotations

import sys
from pathlib import Path

try:
    import yaml  # pip install pyyaml
except ImportError:
    print("Missing dependency: pyyaml. Install with: pip install pyyaml", file=sys.stderr)
    raise

ICON = {
    "available": "✅",
    "wip": "⚠️",
    "not_implemented": "❌",
}

def load_master(path: Path) -> dict:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("Master file must be a YAML dict.")
    return data

def build_html(data: dict) -> str:
    ics = data["ics"]
    models = data["models"]
    status = data["status"]

    parts = []
    parts.append('<table><tr><td>')
    parts.append('<b>The current implementation supports the following ICs / AI models:</b><br><br>')

    # Inner table
    parts.append('<table>')

    # Header row: Model | Supported modes | Checkpoint | ICs...
    parts.append('<tr>')
    parts.append('<th>Model</th>')
    parts.append('<th>Supported modes</th>')
    parts.append('<th>Checkpoint</th>')
    for ic in ics:
        parts.append(f'<th>{escape(ic)}</th>')
    parts.append('</tr>')

    # Body: model grouped with rowspan, each checkpoint is one row
    for m in models:
        model_name = m["name"]
        ckpts = m.get("checkpoints", [])
        if not ckpts:
            continue

        parts.append('<tr>')
        # model cell with rowspan across its checkpoints
        parts.append(f'<td rowspan="{len(ckpts)}"><b>{escape(model_name)}</b></td>')
        parts.append(f'<td rowspan="{len(ckpts)}">{escape(str(m.get("supported_modes", "-")))}</td>')

        # first checkpoint row
        first = True
        for ckpt in ckpts:
            if not first:
                parts.append('<tr>')

            label = escape(ckpt["label"])
            url = ckpt.get("url", "").strip()
            ckpt_id = ckpt["id"]

            # checkpoint cell (with link if present)
            if url:
                parts.append(f'<td><a href="{escape_attr(url)}">{label}</a></td>')
            else:
                parts.append(f'<td>{label}</td>')

            # status cells for each IC
            for ic in ics:
                st = status.get(ic, {}).get(ckpt_id, "not_implemented")
                icon = ICON.get(st, "❌")
                parts.append(f'<td align="center">{icon}</td>')

            parts.append('</tr>')
            first = False

    parts.append('</table>')  # end inner table
    parts.append('</td>')

    # Legend (right side)
    parts.append('<td style="padding-left:20px; vertical-align:top;">')
    parts.append('<b> </b><br><br>')
    parts.append('<b> </b><br><br>')
    parts.append('✅ available<br>')
    parts.append('⚠️ work in progress<br>')
    parts.append('❌ not implemented<br>')
    parts.append('</td></tr></table>')

    return "\n".join(parts)

def escape(s: str) -> str:
    return (s.replace("&", "&amp;")
             .replace("<", "&lt;")
             .replace(">", "&gt;"))

def escape_attr(s: str) -> str:
    # minimal attribute escaping
    return escape(s).replace('"', "&quot;")

START = "<!-- support-matrix:start (generated by docs/generate_table.py, do not edit) -->"
END = "<!-- support-matrix:end -->"


def update_readme(readme: Path, html: str) -> bool:
    """Replace the table between the markers in the README. Returns True if it changed."""
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no support-matrix markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n{html}\n{END}{tail}"
    if new != text:
        readme.write_text(new, encoding="utf-8")
    return new != text


def main():
    """Usage: generate_table.py [support-matrix.yml] [output.html | README.md]

    With a README path the table between the support-matrix markers is replaced in place.
    """
    master = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("support-matrix.yml")
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("generated-table.html")

    data = load_master(master)
    html = build_html(data)
    if out.suffix.lower() == ".md":
        changed = update_readme(out, html)
        print(f"{'Updated' if changed else 'Unchanged'}: {out}")
    else:
        out.write_text(html + "\n", encoding="utf-8")
        print(f"Wrote {out}")


if __name__ == "__main__":
    main()
